export type Demo = (typeof demos)[number];
export type DemoPath = Demo['path'];
export const categories = ['All', 'Templates', 'Components', 'Effects', 'Tools'] as const;
export type Category = (typeof categories)[number];
export function filterDemos(query: string, category: Category = 'All') {
  const words = query.toLowerCase().trim().split(/\s+/).filter(Boolean);
  return demos.filter(
    (demo) =>
      (category === 'All' || demo.category === category) &&
      words.every((word) =>
        `${demo.title} ${demo.description} ${demo.medium}`.toLowerCase().includes(word),
      ),
  );
}
